def sect(name):
    i = next(k for k, l in enumerate(L) if l.startswith("\\subsubsection{" + name + "}"))
    j = i + 1
    while j < len(L) and not re.match(r"\\(sub)?(sub)?section\{", L[j]) and not L[j].lstrip().startswith("\\begin{table}"):
        j += 1
    return "\n".join(L[i:j])


def han(t):
    return len(re.findall(r"[一-鿿]", t))


